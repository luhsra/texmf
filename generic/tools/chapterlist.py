#!/usr/bin/env python3
"""Generate make chapter ranges; comment out entries marked disabled by Typst."""

from pathlib import Path
import re
import json
import sys
import unicodedata


def heading_text(content):
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "".join(map(heading_text, content))
    for key in ("text", "children", "body", "child"):
        if key in content:
            return heading_text(content[key])
    raise ValueError(f"Unsupported heading content: {content!r}")


def chapterlist(metadata):
    chapters = [
        (heading_text(chapter["title"]), chapter["page"], chapter.get("disabled", False))
        for chapter in metadata["chapters"]
    ]
    page_count = metadata["pages"]
    if not chapters:
        raise ValueError("Expected level-2 headings in the Typst query")

    parts = []
    ranges = []
    for index, (title, start, disabled) in enumerate(chapters):
        # ASCII filenames remain usable as both make variables and PDF basenames.
        title = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode()
        slug = re.sub(r"[^A-Za-z0-9]+", "-", title).strip("-")
        part = f"{index + 1:02d}-{slug}"
        end = chapters[index + 1][1] - 1 if index + 1 < len(chapters) else page_count
        if not 1 <= start <= end <= page_count:
            raise ValueError(f"Invalid chapter range {start}-{end}")
        prefix = "# " if disabled else ""
        parts.append(f"{prefix}PARTS += {part}")
        ranges.append(f"{prefix}{part} = {start}-{end}")

    return "\n".join(
        [
            "# Generated by typst query; page numbers are physical PDF pages.",
            "PARTS :=",
            *parts,
            "",
            *ranges,
            "",
        ]
    )


if __name__ == "__main__":
    output = Path(sys.argv[1])
    output.write_text(chapterlist(json.load(sys.stdin)), encoding="utf-8")
